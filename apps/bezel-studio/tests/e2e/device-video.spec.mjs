import { test, expect, watchErrors, expectAccessible, copyAndPaste, storageFileAction, openSection } from './helpers.mjs';

test('stored screen video becomes theme background with loop, windows and linear transparency', async ({ page, t }) => {
  const errors = watchErrors(page);
  await page.goto('/index.html?demo=vendorCard');
  await page.getByRole('tab', { name: t('library.screen'), exact: true }).click();
  await page.getByRole('tab', { name: t('screen.storageTab'), exact: true }).click();
  const card = page.getByRole('region', { name: t('storage.medium.sd'), exact: true });
  // Each file has its own menu (T-7c): the action applies to that file.
  const setBackground = await storageFileAction(page, t, card, 'AMD.mp4', 'background');
  await expect(setBackground).toBeEnabled();
  await setBackground.click();
  await openSection(page, 'color');
  const detail = page.locator('#inspector');
  await expect(detail).toContainText('AMD.mp4');
  await expect(detail).toContainText(t('deviceVideo.preview'));
  const loop = detail.getByRole('button', { name: t('deviceVideo.loop'), exact: true });
  await expect(loop).toHaveAttribute('aria-pressed', 'true');
  await loop.click();
  await expect(loop).toHaveAttribute('aria-pressed', 'false');
  await page.locator('#undo').click();
  await expect(loop).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: t('library.addWidget', { name: t('common.shape') }), exact: true }).click();
  await openSection(page, 'shape'); await openSection(page, 'color');
  const window = detail.getByRole('button', { name: t('shape.videoWindow'), exact: true });
  await window.click();
  await expect(window).toHaveAttribute('aria-pressed', 'true');
  const fade = detail.getByRole('group', { name: t('fade.mode'), exact: true });
  const fadeMode = (mode) => fade.getByRole('button', { name: t(`fade.${mode}`), exact: true });
  await fadeMode('linear').click();
  await detail.getByLabel(t('shape.fadeAngle'), { exact: true }).fill('90');
  await detail.getByLabel(t('shape.fadeAngle'), { exact: true }).press('Tab');
  const start = detail.getByRole('slider', { name: new RegExp(t('shape.fadeStart')) });
  await start.fill('80'); await start.dispatchEvent('change');
  await copyAndPaste(page);
  await expect(window).toHaveAttribute('aria-pressed', 'true');
  await expect(detail.getByLabel(t('shape.fadeAngle'), { exact: true })).toHaveValue('90');
  await expect(start).toHaveValue('80');
  await fadeMode('none').click();
  await page.locator('#undo').click();
  await expect(fadeMode('linear')).toHaveAttribute('aria-pressed', 'true');
  await expectAccessible(page);
  expect(errors).toEqual([]);
});
