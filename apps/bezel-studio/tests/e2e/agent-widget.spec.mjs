  await expect(age()).toHaveAttribute('aria-pressed', 'true');
  await age().click();
  await expect(age()).toHaveAttribute('aria-pressed', 'false');
  const position = () => panel.getByRole('group', { name:t('agent.statePosition'), exact:true });
  await position().getByRole('button', { name:t('agent.stateBelow'), exact:true }).click();
  await expect(position().getByRole('button', { name:t('agent.stateBelow'), exact:true })).toHaveAttribute('aria-pressed', 'true');
  await expect(panel.getByRole('spinbutton', { name:t('agent.quotaSizePercent'), exact:true })).toHaveCount(0);
