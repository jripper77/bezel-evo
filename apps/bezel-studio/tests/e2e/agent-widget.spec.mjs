import { test, expect, clickAddWidget, openSection, expectAccessible, watchErrors } from './helpers.mjs';

test('dedicated agent widgets have provider-specific details and adaptive project controls', async ({ page, t }) => {
  const errors = watchErrors(page);
  await page.goto('/index.html?demo=turing88');
  await clickAddWidget(page, t, 'codex');
  const panel = page.locator('#inspector');
  await openSection(page, 'data');
  const view = value => panel.getByRole('group', { name:t('agent.view'), exact:true }).getByRole('button', { name:t(value === 'projects' ? 'agent.projectList' : 'agent.singleSession'), exact:true });
  await expect(view('projects')).toHaveAttribute('aria-pressed', 'true');
  await expect(panel.getByRole('button', { name:t('agent.connectClaude'), exact:true })).toHaveCount(0);
  const recent = panel.getByRole('spinbutton', { name:t('agent.recentMinutes'), exact:true });
  await recent.fill('30'); await recent.press('Tab');
  await expect(recent).toHaveValue('30');
  await view('session').click();
  await expect(panel.getByRole('combobox', { name:t('agent.project'), exact:true })).toHaveValue('');
  await expect(panel.getByRole('combobox', { name:t('agent.session'), exact:true })).toHaveValue('');
  await page.locator('#undo').click();
  await expect(view('projects')).toHaveAttribute('aria-pressed', 'true');
  await clickAddWidget(page, t, 'claude');
  await openSection(page, 'data');
  await expect(view('projects')).toHaveAttribute('aria-pressed', 'true');
  await expect(recent).toHaveValue('10');
  await expect(panel.getByRole('button', { name:t('agent.connectClaude'), exact:true })).toBeVisible();
  await expectAccessible(page);
  expect(errors).toEqual([]);
});

const openPart = async (page, t, key) => {
  await openSection(page, 'parts');
  const label = t({ title: 'insp.partTitle', rows: 'agent.rows', fiveHour: 'agent.showFiveHour', weekly: 'agent.showWeekly', content: 'inspector.content' }[key]);
  await page.locator('#inspector').getByRole('button', { name: t('agent.openPart', { part: label }), exact: true }).click();
};

